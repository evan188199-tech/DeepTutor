"""Native Gemini speech synthesis through ``generateContent``.

Gemini TTS models are not served on the OpenAI-compatible ``/audio/speech``
route — the vendor's compatibility mount answers 404 for them. Speech is
generated by the native ``models/{model}:generateContent`` call with audio
response modalities, which replies with base64 PCM16 (24 kHz mono) wrapped in
``inlineData``.

Protocol: https://ai.google.dev/gemini-api/docs/speech-generation
"""

from __future__ import annotations

import base64
import binascii
from typing import Any

import httpx

from deeptutor.services.voice.audio import pcm_to_wav
from deeptutor.services.voice.base import (
    BaseTTSAdapter,
    VoiceProviderError,
    VoiceProviderHTTPError,
)
from deeptutor.services.voice.config import TTSConfig

# The documented default prebuilt voice, used when a model saves no voice.
DEFAULT_PREBUILT_VOICE = "Kore"
_DEFAULT_SAMPLE_RATE = 24000
_GEMINI_TTS_FORMATS = {"wav", "pcm"}


def _synthesis_url(config: TTSConfig) -> str:
    """Point ``generateContent`` at the native API base, whatever the profile saved.

    A Gemini connection stores the vendor's OpenAI-compatible mount (``.../v1beta/openai``)
    for chat; TTS lives one level up on the same host, so that suffix is stripped.
    A URL already ending in ``:generateContent`` is an explicit endpoint and stays verbatim.
    """
    base = (config.base_url or "").strip()
    if not base:
        raise VoiceProviderError("No endpoint URL configured for TTS.")
    head, sep, query = base.partition("?")
    head = head.rstrip("/")
    if head.endswith("/openai"):
        head = head[: -len("/openai")]
    model = config.model.strip().lstrip("/").removeprefix("models/").strip("/")
    if not model:
        raise VoiceProviderError(
            "Enter a Gemini TTS model ID such as gemini-2.5-flash-preview-tts."
        )
    if head.endswith(":generateContent"):
        return base
    url = f"{head}/models/{model}:generateContent"
    return f"{url}?{query}" if sep else url


def _request_payload(text: str, config: TTSConfig) -> dict[str, Any]:
    # Style prompting is part of the spoken prompt itself, per the vendor docs.
    prompt = f"{config.instructions}: {text}" if config.instructions else text
    return {
        "contents": [{"parts": [{"text": prompt}]}],
        "generationConfig": {
            "responseModalities": ["AUDIO"],
            "speechConfig": {
                "voiceConfig": {
                    "prebuiltVoiceConfig": {
                        "voiceName": (config.voice or "").strip() or DEFAULT_PREBUILT_VOICE
                    }
                }
            },
        },
    }


def _sample_rate(mime_type: str) -> int:
    """Read the rate parameter from an ``inlineData`` MIME type (``audio/L16;rate=24000``)."""
    for parameter in mime_type.split(";")[1:]:
        key, separator, value = parameter.strip().partition("=")
        if separator and key.strip().lower() == "rate":
            try:
                parsed = int(value)
            except ValueError:
                continue
            if parsed > 0:
                return parsed
    return _DEFAULT_SAMPLE_RATE


def _audio_part(payload: dict[str, Any]) -> tuple[bytes, int]:
    candidates = payload.get("candidates")
    parts = candidates[0].get("content", {}).get("parts", []) if candidates else []
    for part in parts:
        if not isinstance(part, dict):
            continue
        inline = part.get("inlineData") or part.get("inline_data")
        if isinstance(inline, dict) and isinstance(inline.get("data"), str):
            try:
                audio = base64.b64decode(inline["data"], validate=True)
            except (binascii.Error, ValueError) as exc:
                raise VoiceProviderError("Gemini TTS returned malformed base64 audio.") from exc
            if audio:
                mime = str(inline.get("mimeType") or inline.get("mime_type") or "")
                return audio, _sample_rate(mime)
    raise VoiceProviderError("Gemini TTS returned no audio.")


class GeminiTTSAdapter(BaseTTSAdapter):
    """Synthesize speech with Gemini's native ``generateContent`` speech protocol."""

    async def synthesize(self, text: str, config: TTSConfig) -> tuple[bytes, str]:
        """Return WAV audio, or raw PCM16 when that format is selected."""
        audio_format = (config.response_format or "wav").strip().lower()
        if audio_format == "pcm16":
            audio_format = "pcm"
        if audio_format not in _GEMINI_TTS_FORMATS:
            raise VoiceProviderError(
                "Gemini TTS supports WAV or PCM audio.",
                public_message="Gemini TTS outputs WAV or PCM audio. Select one of them as the audio format.",
            )
        if config.speed is not None:
            raise VoiceProviderError(
                "Gemini TTS does not support a speed setting.",
                public_message=(
                    "Gemini TTS does not support a speech speed setting. "
                    "Clear it or guide the pace with voice instructions."
                ),
            )
        headers = {"Content-Type": "application/json", **config.extra_headers}
        if config.api_key:
            headers["x-goog-api-key"] = config.api_key
        try:
            async with httpx.AsyncClient(timeout=config.request_timeout) as client:
                response = await client.post(
                    _synthesis_url(config),
                    headers=headers,
                    json=_request_payload(text, config),
                )
        except httpx.HTTPError as exc:
            raise VoiceProviderError("Gemini TTS connection failed or timed out.") from exc
        if response.status_code >= 400:
            # Status only: an upstream body is neither logged nor surfaced.
            raise VoiceProviderHTTPError(
                f"Gemini TTS synthesis failed with HTTP {response.status_code}.",
                status_code=response.status_code,
            )
        try:
            payload = response.json()
        except ValueError as exc:
            raise VoiceProviderError("Gemini TTS returned an invalid response.") from exc
        if not isinstance(payload, dict):
            raise VoiceProviderError("Gemini TTS returned an invalid response.")
        audio, sample_rate = _audio_part(payload)
        if audio_format == "pcm":
            return audio, f"audio/pcm;rate={sample_rate};channels=1"
        return pcm_to_wav(audio, sample_rate=sample_rate), "audio/wav"
